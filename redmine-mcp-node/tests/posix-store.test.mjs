const posix = { skip: !['linux', 'darwin'].includes(process.platform) };
async function fixture(t) {
  const dir = await realpath(await mkdtemp(join(tmpdir(), 'redmine-posix-')));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const root = join(dir, 'cache'), start = new Date('2026-01-01T00:00:00Z');
  const store = createPosixAttachmentStore({ root, clock: () => start });
  return { dir, root, start, store };
}
async function publish(store) {
  const stage = await store.stageDownload('https://example.com', '原始.txt');
  stage.writer.end('hello');
  await finished(stage.writer);
  return store.publish(stage);
}
function locations(file) {
  const item = dirname(file), site = dirname(dirname(item)), id = basename(item);
  return { record: join(site, 'records', id + '.json'), archive: join(site, 'archives', id + '.zip') };
}
const day = 86_400_000;

test('archive codec accepts Python ZIPs and verifies the generated bytes through retained descriptors', async (t) => {
  const dir = await mkdtemp(join(tmpdir(), 'redmine-zip-'));
  try {
    const source = await open(join(dir, 'source'), 'wx+'), zip = await open(join(dir, 'archive'), 'wx+');
    try {
      await source.writeFile('hello');
      const record = { filename: '原始.txt', ...await fingerprint(source.fd) };
      assert.equal(record.sha256, '2cf24dba5fb0a30e26e83b2ac5b9e29e1b161e5c1fa7425e73043362938b9824');
      await writeArchive(source.fd, zip.fd, record);
      assert.equal(await readFile(join(dir, 'source'), 'utf8'), 'hello');
      await verifyArchive(zip.fd, record);
      // Python zipfile.ZipFile.writestr with ZIP_DEFLATED, one UTF-8 member containing "hello".
      const pythonZip = 'UEsDBBQAAAgIAAAAIVyGphA2BwAAAAUAAAAKAAAA5Y6f5aeLLnR4dMtIzcnJBwBQSwECFAAUAAAICAAAACFchqYQNgcAAAAFAAAACgAAAAAAAAAAAAAAgAEAAAAA5Y6f5aeLLnR4dFBLBQYAAAAAAQABADgAAAAvAAAAAAA=';
      await zip.truncate(0); await zip.write(Buffer.from(pythonZip, 'base64'), 0, Buffer.byteLength(pythonZip, 'base64'), 0);
      await verifyArchive(zip.fd, record);
      await assert.rejects(verifyArchive(zip.fd, { ...record, sha256: '0'.repeat(64) }));
    } finally { await zip.close(); await source.close(); }
  } finally { await rm(dir, { recursive: true, force: true }); }
});

test('POSIX cache creates private v1 items and performs the seven- and thirty-day transitions', posix, async (t) => {
  const { root, store, start } = await fixture(t);
  await store.sweep();
  await assert.rejects(stat(root), { code: 'ENOENT' });
  const path = await publish(store), { record, archive } = locations(path);
  assert.equal((await stat(root)).mode & 0o777, 0o700);
  assert.equal((await stat(path)).mode & 0o777, 0o600);
  assert.equal((await stat(record)).mode & 0o777, 0o600);
  assert.equal((await store.borrowSource(path, 5, null)).toString(), 'hello');
  await assert.rejects(store.borrowSource(path, 4, null));
  await store.sweep(new Date(+start + 7 * day - 1));
  assert.equal(await readFile(path, 'utf8'), 'hello');
  await store.sweep(new Date(+start + 7 * day));
  assert.equal(JSON.parse(await readFile(record)).state, 'archived');
  assert.equal((await readFile(archive)).readUInt32LE(0), 0x04034b50);
  await assert.rejects(stat(path), { code: 'ENOENT' });
  await store.sweep(new Date(+start + 37 * day - 1));
  assert.ok((await stat(archive)).size > 0);
  await store.sweep(new Date(+start + 37 * day));
  for (const gone of [record, archive]) await assert.rejects(stat(gone), { code: 'ENOENT' });
});

test('POSIX configured sources and staging respect file boundaries and existing private permissions', posix, async (t) => {
  const { dir, root, store } = await fixture(t);
  await mkdir(join(dir, 'upload'), { mode: 0o700 });
  await chmod(join(dir, 'upload'), 0o755);
  await mkdir(join(dir, 'upload/sub'), { mode: 0o755 });
  const ordinary = join(dir, 'upload/sub/report.txt');
  await writeFile(ordinary, 'user file'); await chmod(ordinary, 0o644);
  assert.equal((await store.borrowSource(ordinary, 9, join(dir, 'upload'))).toString(), 'user file');
  await chmod(ordinary, 0o664);
  await assert.rejects(store.borrowSource(ordinary, 9, join(dir, 'upload')));
  await chmod(ordinary, 0o644); await chmod(dirname(ordinary), 0o775);
  await assert.rejects(store.borrowSource(ordinary, 9, join(dir, 'upload')));
  await mkdir(root, { mode: 0o700 }); await chmod(root, 0o755);
  await assert.rejects(publish(store));
  assert.equal((await stat(root)).mode & 0o777, 0o755);
  const allowed = join(dir, 'in');
  await mkdir(allowed, { mode: 0o700 });
  const file = join(allowed, 'source'), outside = join(dir, 'other');
  await writeFile(file, 'good', { mode: 0o600 }); await writeFile(outside, 'outside', { mode: 0o600 });
  assert.equal((await store.borrowSource(file, 4, allowed)).toString(), 'good');
  await assert.rejects(store.borrowSource(outside, 100, allowed));
  await assert.rejects(store.borrowSource(file, 100, null));
  await symlink(outside, join(allowed, 'redirect')); await link(outside, join(allowed, 'other-link'));
  for (const leaf of ['redirect', 'other-link']) await assert.rejects(store.borrowSource(join(allowed, leaf), 100, allowed));
  await chmod(root, 0o700);
  const stage = await store.stageDownload('https://example.com', 'item.txt');
  await store.discard(stage);
  await assert.rejects(store.publish(stage));
});

test('POSIX recovery retains uncertain archives and resumes a valid published record after a crash', posix, async (t) => {
  const { store, start } = await fixture(t);
  const path = await publish(store), { record, archive } = locations(path);
  await store.sweep(new Date(+start + 7 * day));
  const originalZip = await readFile(archive);
  const rec = JSON.parse(await readFile(record));
  rec.state = 'archive_published';
  await writeFile(record, JSON.stringify(rec)); await writeFile(path, 'hello', { mode: 0o600 });
  await writeFile(archive, 'corrupt');
  await store.sweep(new Date(+start + 8 * day));
  assert.equal(await readFile(path, 'utf8'), 'hello');
  assert.equal(JSON.parse(await readFile(record)).state, 'archive_published');
  await writeFile(archive, originalZip);
  await store.sweep(new Date(+start + 8 * day));
  await assert.rejects(stat(path), { code: 'ENOENT' });
  assert.equal(JSON.parse(await readFile(record)).state, 'archived');
});

test('POSIX publisher rejects stage contents changed after receipt', posix, async (t) => {
  const { store, root } = await fixture(t);
  const stage = await store.stageDownload('https://example.com', 'report.txt');
  stage.writer.end('hello'); await finished(stage.writer);
  const [key] = await readdir(root), [id] = await readdir(join(root, key, 'active'));
  const item = join(root, key, 'active', id);
  await writeFile(join(item, '.download.part'), 'other');
  await assert.rejects(store.publish(stage));
  await assert.rejects(stat(join(item, '.download.part')), { code: 'ENOENT' });
  await assert.rejects(stat(join(root, key, 'records', id + '.json')), { code: 'ENOENT' });
});

test('an actual legacy Python cache under umask 022 can be borrowed and archived by Node', {
  skip: posix.skip || !process.env.STORAGE_TEST_PYTHON,
}, async (t) => {
  const { root, store, start } = await fixture(t);
  const python = (code, ...args) => execFileSync(process.env.STORAGE_TEST_PYTHON, ['-c', code, root, ...args], {
    encoding: 'utf8',
    env: { ...process.env, PYTHONPATH: fileURLToPath(new URL('../../redmine-mcp/src/', import.meta.url)), PYTHONUTF8: '1' },
  }).trim();
  const created = JSON.parse(python([
    'import json, os, stat, sys',
    'from datetime import datetime, timezone',
    'from pathlib import Path',
    'from redmine_mcp.attachment_storage.store import AttachmentStore',
    'os.umask(0o022)',
    'root = Path(sys.argv[1])',
    's = AttachmentStore(root, clock=lambda: datetime(2026, 1, 1, tzinfo=timezone.utc))',
    'with s.begin_download("https://example.com", "python.txt") as p:',
    '    with p.open_writer() as output: output.write(b"from python")',
    '    result = p.publish()',
    'print(json.dumps({"path": str(result), "files": sorted(set(stat.S_IMODE(p.stat().st_mode) for p in root.rglob("*") if p.is_file())), "dirs": sorted(set(stat.S_IMODE(p.stat().st_mode) for p in [root, *root.rglob("*")] if p.is_dir()))}))',
  ].join('\n')));
  assert.deepEqual(created.files, [0o600]);
  assert.deepEqual(created.dirs, [0o700]);
  assert.equal((await store.borrowSource(created.path, 100, null)).toString(), 'from python');
  await store.sweep(new Date(+start + 7 * day));
  const { archive, record } = locations(created.path);
  assert.equal(JSON.parse(await readFile(record)).state, 'archived');
  assert.equal(python('from zipfile import ZipFile\nimport sys\nwith ZipFile(sys.argv[2]) as z: print(z.read("python.txt").decode())', archive), 'from python');
});
